EOF

# Create the IAM policy
POLICY_ARN=$(aws iam create-policy --policy-name AWSLoadBalancerControllerIAMPolicy --policy-document file://alb-controller-policy.json --query 'Policy.Arn' --output text)

# Create IAM role trust policy
echo "🔧 Creating IAM role trust policy..."
cat > alb-controller-trust-policy.json << EOF
{
  "Version": "2012-10-17",
  "Statement": [
    {
      "Effect": "Allow",
      "Principal": {
        "Federated": "arn:aws:iam::${ACCOUNT_ID}:oidc-provider/${OIDC_PROVIDER}"
      },
      "Action": "sts:AssumeRoleWithWebIdentity",
      "Condition": {
        "StringEquals": {
          "${OIDC_PROVIDER}:aud": "sts.amazonaws.com",
          "${OIDC_PROVIDER}:sub": "system:serviceaccount:kube-system:aws-load-balancer-controller"
        }
      }
    }
  ]
}
EOF

# Create the IAM role
echo "🔧 Creating IAM role..."
ROLE_NAME="AmazonEKSLoadBalancerControllerRole"
aws iam create-role --role-name ${ROLE_NAME} --assume-role-policy-document file://alb-controller-trust-policy.json

# Attach the policy to the role
echo "🔧 Attaching policy to role..."
aws iam attach-role-policy --role-name ${ROLE_NAME} --policy-arn ${POLICY_ARN}

# Create service account
echo "🔧 Creating service account..."
cat > alb-controller-service-account.yaml << EOF
apiVersion: v1
kind: ServiceAccount
metadata:
  labels:
    app.kubernetes.io/component: controller
    app.kubernetes.io/name: aws-load-balancer-controller
  name: aws-load-balancer-controller
  namespace: kube-system
  annotations:
    eks.amazonaws.com/role-arn: arn:aws:iam::${ACCOUNT_ID}:role/${ROLE_NAME}
EOF

kubectl apply -f alb-controller-service-account.yaml

# Install the controller
echo "🔧 Installing AWS Load Balancer Controller..."
helm install aws-load-balancer-controller eks/aws-load-balancer-controller \
  -n kube-system \
  --set clusterName=${CLUSTER_NAME} \
  --set serviceAccount.create=false \
  --set serviceAccount.name=aws-load-balancer-controller \
  --set region=${REGION} \
  --set vpcId=$(aws eks describe-cluster --name ${CLUSTER_NAME} --region ${REGION} --query "cluster.resourcesVpcConfig.vpcId" --output text)

# Wait for the controller to be ready
echo "⏳ Waiting for AWS Load Balancer Controller to be ready..."
kubectl -n kube-system wait --for=condition=available --timeout=300s deployment/aws-load-balancer-controller

echo "✅ AWS Load Balancer Controller installed successfully."

# Clean up
rm -f alb-controller-policy.json alb-controller-trust-policy.json alb-controller-service-account.yaml